#!/usr/bin/env python3
"""MLP nhỏ dự báo T(t+3), dùng lại temperature.csv (timestamp UTC, temperature).
Cài: python -m pip install numpy pandas scikit-learn
Chạy: python Training_MLP.py --csv temperature.csv --verify-cpp
Xuất C_model_MLP.cpp tự chứa trọng số; biên dịch bằng C++17, không cần thư viện ML.
C++ là golden model floating-point double, CHƯA phải fixed-point/bit-exact RTL.
Các CSV/JSON trong mlp_output là kết quả chạy, không phải file nguồn bắt buộc.
"""
import os
for _key in ('OPENBLAS_NUM_THREADS', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS'):
    os.environ.setdefault(_key, '1')
import argparse
import copy
import json
from pathlib import Path
import subprocess
import numpy as np
import pandas as pd
from sklearn.neural_network import MLPRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Ridge

FEATURES = ['delta24', 'delta01', 'delta12', 'delta23', 'delta2122',
            'delta2223', 'current', 'anchor', 'delta6', 'delta12h', 'sin_hour', 'cos_hour']
TAPS = [0, 1, 2, 3, 6, 12, 21, 22, 23, 24]

# C++ weights are replaced at export time. predict_model_mlp accepts a full
# contiguous window: history[0]=T(t-24), ..., history[24]=T(t).
CPP_TEMPLATE = r'''// Generated by Training_MLP.py. Do not hand-edit weights.
// Model: 12 -> 16 ReLU -> 1 residual, plus diurnal anchor T(t-21).
// Floating-point golden model (double); NOT a fixed-point RTL reference yet.
// Build: g++ -std=c++17 -O2 C_model_MLP.cpp -o mlp
// Demo: ./mlp
// Batch: ./mlp --batch < mlp_output/test_vectors_mlp.txt > cpp_predictions.txt
// Batch row: hour_utc T(t) T(t-1) T(t-2) T(t-3) T(t-6) T(t-12)
//            T(t-21) T(t-22) T(t-23) T(t-24)
// Stream use: retain 25 consecutive hourly observations before calling;
// reset the buffer after a missing hour. A pause in replay is not a missing hour.
#include <algorithm>
#include <array>
#include <cmath>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
namespace {
constexpr int INPUTS=12, HIDDEN=16;
constexpr double PI=3.141592653589793238462643383279502884;
// Training-only input scaling has been folded into W1/B1.
@WEIGHTS@
}

double predict_model_mlp(const std::array<double,25>& history, int hour_utc) {
    if (hour_utc < 0 || hour_utc > 23) throw std::invalid_argument("hour_utc must be 0..23");
    for (double t: history)
        if (!std::isfinite(t) || t == -999.0) throw std::invalid_argument("Invalid temperature");
    const auto T = [&](int lag) { return history[24-lag]; };
    const double angle=2.0*PI*hour_utc/24.0;
    const std::array<double,INPUTS> x={
        T(0)-T(24),T(0)-T(1),T(1)-T(2),T(2)-T(3),
        T(21)-T(22),T(22)-T(23),T(0),T(21),
        T(0)-T(6),T(0)-T(12),std::sin(angle),std::cos(angle)};
    double residual=B2;
    for (int j=0;j<HIDDEN;++j) {
        double z=B1[j];
        for (int i=0;i<INPUTS;++i) z+=x[i]*W1[i][j];
        residual+=std::max(0.0,z)*W2[j];
    }
    return T(21)+residual;
}

#ifndef MLP_NO_MAIN
int main(int argc,char** argv) {
    try {
        std::cout<<std::setprecision(17);
        if (argc==2 && std::string(argv[1])=="--batch") {
            std::string line;
            constexpr int lags[10]={0,1,2,3,6,12,21,22,23,24};
            int line_number=0;
            while (std::getline(std::cin,line)) {
                ++line_number;
                if (line.find_first_not_of(" \t\r")==std::string::npos) continue;
                std::istringstream row(line);
                int hour;
                std::array<double,25> history{};
                if (!(row>>hour)) throw std::runtime_error("Invalid hour at line "+std::to_string(line_number));
                for (int lag:lags)
                    if (!(row>>history[24-lag])) throw std::runtime_error("Missing/invalid tap at line "+std::to_string(line_number));
                std::string extra;
                if (row>>extra) throw std::runtime_error("Extra field at line "+std::to_string(line_number));
                // Batch format contains the ten required taps only; full-window
                // continuity was checked by the Python vector generator.
                std::cout<<predict_model_mlp(history,hour)<<'\n';
            }
            return 0;
        }
        if (argc!=1) throw std::runtime_error("Usage: mlp [--batch]");
        std::array<double,25> history{};
        history.fill(20.0); // Synthetic example, not measured weather.
        std::cout<<"Example forecast +3h (25 samples at 20 C, current UTC hour 6): "
                 <<predict_model_mlp(history,6)<<" C\n";
    } catch(const std::exception& e) {
        std::cerr<<"Error: "<<e.what()<<'\n'; return 1;
    }
}
#endif
'''


def load_data(csv):
    df = pd.read_csv(csv)
    if not {'timestamp', 'temperature'}.issubset(df.columns):
        raise ValueError('CSV cần hai cột timestamp, temperature.')
    idx = pd.to_datetime(df['timestamp'], utc=True, errors='raise')
    if idx.isna().any() or idx.duplicated().any():
        raise ValueError('Timestamp thiếu hoặc trùng.')
    if not idx.eq(idx.dt.floor('h')).all():
        raise ValueError('Timestamp phải nằm đúng đầu giờ.')
    values = pd.to_numeric(df['temperature'], errors='raise').to_numpy(dtype=float)
    T = pd.Series(values, index=pd.DatetimeIndex(idx)).sort_index().asfreq('h')
    T = T.where(np.isfinite(T) & T.ne(-999.0))
    data = pd.DataFrame(index=T.index)
    for lag in TAPS:
        data[f't{lag}'] = T.shift(lag)
    data['delta24'] = T-T.shift(24)
    data['delta01'] = T-T.shift(1)
    data['delta12'] = T.shift(1)-T.shift(2)
    data['delta23'] = T.shift(2)-T.shift(3)
    data['delta2122'] = T.shift(21)-T.shift(22)
    data['delta2223'] = T.shift(22)-T.shift(23)
    data['current'], data['anchor'] = T, T.shift(21)
    data['delta6'], data['delta12h'] = T-T.shift(6), T-T.shift(12)
    data['hour_utc'] = data.index.hour
    angle = 2*np.pi*data['hour_utc']/24
    data['sin_hour'], data['cos_hour'] = np.sin(angle), np.cos(angle)
    data['truth'] = T.shift(-3)
    data['y'] = data['truth']-data['anchor']
    data['target_time'] = data.index+pd.Timedelta(hours=3)
    # Never interpolate using future samples; gaps invalidate the 25-hour window.
    data = data.loc[T.rolling(25, min_periods=25).count().eq(25)].dropna()
    print(f'Hourly rows={len(T)}, missing={T.isna().sum()}, usable={len(data)}', flush=True)
    return data


def score(truth, pred):
    e = np.asarray(pred)-np.asarray(truth)
    return {'MAE_C': float(np.mean(np.abs(e))),
            'RMSE_C': float(np.sqrt(np.mean(e*e))), 'bias_C': float(np.mean(e))}


def old_X(rows):
    return np.column_stack([rows['delta24'], rows['t0']-rows['t3'], np.ones(len(rows))])


def export_cpp(model, scaler, path):
    # z=(x-mu)/sigma; z@W+b = x@(W/sigma)+(b-mu@(W/sigma)).
    W1 = model.coefs_[0]/scaler.scale_[:, None]
    B1 = model.intercepts_[0]-scaler.mean_@W1
    W2, B2 = model.coefs_[1][:, 0], float(model.intercepts_[1][0])
    def arr(x):
        if np.ndim(x)==0:
            return format(float(x), '.17g')
        return '{'+', '.join(arr(v) for v in x)+'}'
    weights = (f'constexpr double W1[INPUTS][HIDDEN]={arr(W1)};\n'
               f'constexpr double B1[HIDDEN]={arr(B1)};\n'
               f'constexpr double W2[HIDDEN]={arr(W2)};\n'
               f'constexpr double B2={arr(B2)};\n')
    path.write_text(CPP_TEMPLATE.replace('@WEIGHTS@', weights), encoding='utf-8')
    return W1, B1, W2, B2


def main():
    base = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--csv', type=Path, default=base/'temperature.csv')
    ap.add_argument('--out-dir', type=Path, default=base/'mlp_output')
    ap.add_argument('--cpp', type=Path, default=base/'C_model_MLP.cpp')
    ap.add_argument('--epochs', type=int, default=250)
    ap.add_argument('--patience', type=int, default=30)
    ap.add_argument('--seed', type=int, default=42)
    ap.add_argument('--verify-cpp', action='store_true', help='Requires g++ in PATH')
    args = ap.parse_args()
    if args.epochs<1 or args.patience<1:
        ap.error('epochs và patience phải dương')
    data = load_data(args.csv)
    val_start, test_start = pd.Timestamp('2024-01-01', tz='UTC'), pd.Timestamp('2025-01-01', tz='UTC')
    train = data[data['target_time']<val_start]
    val = data[(data.index>=val_start) & (data['target_time']<test_start)]
    test = data[data.index>=test_start]
    if min(len(train), len(val), len(test))==0:
        raise ValueError('Cần train trước 2024, validation năm 2024, test từ 2025.')
    print(f'Train={len(train)}, validation={len(val)}, test={len(test)}', flush=True)
    # Only train fits scaler/weights. Chronological validation selects alpha/epoch.
    scaler = StandardScaler().fit(train[FEATURES].to_numpy())
    Ztr, Zval = [scaler.transform(r[FEATURES].to_numpy()) for r in (train, val)]
    y = train['y'].to_numpy()
    winner, best_mae = None, np.inf
    log = []
    for alpha in (0.001, 0.1):
        net = MLPRegressor(hidden_layer_sizes=(16,), activation='relu', solver='adam',
                           alpha=alpha, batch_size=256, learning_rate_init=0.001,
                           shuffle=True, random_state=args.seed, early_stopping=False)
        local_best, stale = np.inf, 0
        for epoch in range(1, args.epochs+1):
            # partial_fit = one epoch; no random validation split or future labels.
            net.partial_fit(Ztr, y)
            mae = score(val['truth'], val['anchor'].to_numpy()+net.predict(Zval))['MAE_C']
            log.append({'alpha': alpha, 'epoch': epoch, 'validation_MAE_C': mae})
            if mae < best_mae:
                best_mae = mae
                winner = (copy.deepcopy(net), alpha, epoch)
            if mae < local_best-1e-5:
                local_best, stale = mae, 0
            else:
                stale += 1
            if epoch==1 or epoch%25==0:
                print(f'alpha={alpha:g}, epoch={epoch}, validation MAE={mae:.6f}', flush=True)
            if stale>=args.patience:
                break
    net, alpha, epoch = winner
    print(f'Selected alpha={alpha:g}, epoch={epoch}, validation MAE={best_mae:.6f}', flush=True)
    # Fair comparisons: retrain the two existing model formulas on the same train.
    ols = np.linalg.lstsq(old_X(train), y, rcond=None)[0]
    ridge_scaler = StandardScaler().fit(train[FEATURES[:6]].to_numpy())
    Rtr, Rval = [ridge_scaler.transform(r[FEATURES[:6]].to_numpy()) for r in (train, val)]
    ridge_options = []
    for a in (0.01, 0.1, 1., 10., 100., 1000.):
        m = Ridge(alpha=a, solver='svd').fit(Rtr, y)
        error = score(val['truth'], val['anchor'].to_numpy()+m.predict(Rval))['MAE_C']
        ridge_options.append((error, a, m))
    _, ridge_alpha, ridge = min(ridge_options, key=lambda v:v[0])
    args.out_dir.mkdir(parents=True, exist_ok=True)
    args.cpp.parent.mkdir(parents=True, exist_ok=True)
    W1, B1, W2, B2 = export_cpp(net, scaler, args.cpp)
    metrics = []
    for split, rows in [('validation', val), ('test', test)]:
        X = rows[FEATURES].to_numpy()
        residual = net.predict(scaler.transform(X))
        folded = np.maximum(0, X@W1+B1)@W2+B2
        np.testing.assert_allclose(folded, residual, rtol=1e-12, atol=1e-10)
        predictions = {
            'Persistence': rows['current'].to_numpy(), 'Diurnal': rows['anchor'].to_numpy(),
            'Model1_OLS': rows['anchor'].to_numpy()+old_X(rows)@ols,
            'Model2_Ridge6': rows['anchor'].to_numpy()+ridge.predict(ridge_scaler.transform(rows[FEATURES[:6]].to_numpy())),
            'MLP_12_16_1': rows['anchor'].to_numpy()+folded}
        result = rows[['target_time', 'truth']].copy()
        for name, pred in predictions.items():
            metrics.append({'split':split, 'model':name, **score(rows['truth'],pred)})
            result[name] = pred
        result.to_csv(args.out_dir/f'{split}_predictions.csv', index_label='timestamp', float_format='%.17g')
    scores = pd.DataFrame(metrics)
    scores.to_csv(args.out_dir/'metrics.csv', index=False)
    pd.DataFrame(log).to_csv(args.out_dir/'training_history.csv', index=False)
    metadata = {'architecture':[12,16,1], 'parameters':225, 'features':FEATURES,
                'horizon_hours':3, 'hour_standard':'UTC', 'anchor':'T(t-21)',
                'seed':args.seed, 'alpha':alpha, 'selected_epoch':epoch,
                'ridge_alpha':ridge_alpha, 'train_target_end_exclusive':str(val_start),
                'validation_target_end_exclusive':str(test_start), 'test_origin_start':str(test_start),
                'sample_counts':{'train':len(train),'validation':len(val),'test':len(test)},
                'W1':W1.tolist(), 'B1':B1.tolist(), 'W2':W2.tolist(), 'B2':B2,
                'input_scaling_folded':True, 'numeric_type':'float64', 'metrics':metrics}
    (args.out_dir/'model_mlp.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    vectors = test[['hour_utc']+[f't{i}' for i in TAPS]].to_numpy()
    vector_path = args.out_dir/'test_vectors_mlp.txt'
    np.savetxt(vector_path, vectors, fmt=['%d']+['%.17g']*len(TAPS))
    print(scores.to_string(index=False), flush=True)
    print(f'Generated: {args.cpp}', flush=True)
    if args.verify_cpp:
        exe = (args.out_dir/('mlp_check.exe' if os.name=='nt' else 'mlp_check')).resolve()
        subprocess.run(['g++','-std=c++17','-O2',str(args.cpp),'-o',str(exe)], check=True)
        with vector_path.open() as f:
            output = subprocess.run([str(exe),'--batch'], stdin=f, capture_output=True, text=True, check=True)
        cpp = np.fromstring(output.stdout, sep='\n')
        expected = test['anchor'].to_numpy()+np.maximum(0,test[FEATURES].to_numpy()@W1+B1)@W2+B2
        if cpp.shape!=expected.shape:
            raise AssertionError('C++ output count differs from Python.')
        np.testing.assert_allclose(cpp, expected, rtol=0, atol=1e-10)
        print(f'C++ PASS: {len(cpp)} vectors, max |C++ - Python|={np.max(np.abs(cpp-expected)):.3g} C')


if __name__=='__main__':
    main()
